import {writeFileSync} from 'node:fs';
const tabs=await(await fetch('http://127.0.0.1:9223/json')).json();
const tab=tabs.find(x=>x.type==='page');
if(!tab)throw new Error('No browser target');
const ws=new WebSocket(tab.webSocketDebuggerUrl);
await new Promise((ok,bad)=>{ws.onopen=ok;ws.onerror=bad});
let id=0;const pending=new Map();
ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id&&pending.has(m.id)){pending.get(m.id)(m);pending.delete(m.id)}};
const send=(method,params={})=>new Promise(ok=>{const call=++id;pending.set(call,ok);ws.send(JSON.stringify({id:call,method,params}))});
await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride',{width:1365,height:900,deviceScaleFactor:1,mobile:false});
await send('Page.navigate',{url:'http://localhost:3000/'});
await new Promise(ok=>setTimeout(ok,850));
let shot=await send('Page.captureScreenshot',{format:'png',fromSurface:true});
writeFileSync('C:/Users/Muhammad Haris/Desktop/MyPortfolio/.runlogs/loader-state.png',Buffer.from(shot.result.data,'base64'));
await new Promise(ok=>setTimeout(ok,3000));
await send('Runtime.evaluate',{expression:"document.getElementById('about')?.scrollIntoView({block:'center'})"});
await new Promise(ok=>setTimeout(ok,1500));
shot=await send('Page.captureScreenshot',{format:'png',fromSurface:true});
writeFileSync('C:/Users/Muhammad Haris/Desktop/MyPortfolio/.runlogs/about-state.png',Buffer.from(shot.result.data,'base64'));
ws.close();
